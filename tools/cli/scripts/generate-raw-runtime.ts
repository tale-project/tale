/**
 * The runtime of a raw sandbox device (services/sandbox/docs/raw.md), embedded
 * in the CLI so the release's `tale` binary is all such a device needs:
 *
 * - the sandbox spawner (services/sandbox/src/server.ts), bundled for Bun with
 *   its lazy backends split into chunks, so the Kubernetes client a raw device
 *   never loads stays an import nobody makes;
 * - runnerd (services/sandbox-runtime/daemon/src/main.ts), one per session;
 * - the runtime image's helper programs (the harness wrappers, Claude Code's
 *   hooks, the git credential helper, the MCP bridges) and its Claude Code
 *   managed settings.
 *
 * Written to src/generated/raw-runtime.ts as a name → text map; `tale sandbox
 * device run` lays it out under the device's root (src/lib/sandbox-device/raw/).
 *
 * Run: bun run scripts/generate-raw-runtime.ts
 */

import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdtemp, readdir, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';

const CLI_ROOT = resolve(dirname(Bun.main), '..');
const REPO_ROOT = resolve(CLI_ROOT, '../..');

/** The runtime image's helper programs a raw session runs by name (or that
 * the platform names under /usr/local/bin): services/sandbox-runtime. */
export const RAW_HELPERS = [
  'tale-connectors-mcp',
  'tale-gemini-run',
  'tale-git-credential',
  'tale-hermes-run',
  'tale-openclaw-run',
  'tale-pi-run',
  'tale-plan-gate',
  'tale-playwright-mcp',
  'tale-qwen-run',
  'tale-steer-hook',
  'tale-vision-read-hook',
  'tale-vision-transcribe',
] as const;

/** Bundled packages a raw device never loads: imported only by the
 * Kubernetes backend and by error reporting with a DSN set. */
const EXTERNAL = ['@kubernetes/client-node', '@sentry/bun'];

async function bundle(
  entry: string,
  name: string,
): Promise<Map<string, string>> {
  const out = await mkdtemp(join(tmpdir(), `tale-raw-${name}-`));
  try {
    const result = await Bun.build({
      entrypoints: [join(REPO_ROOT, entry)],
      target: 'bun',
      format: 'esm',
      splitting: true,
      external: EXTERNAL,
      outdir: out,
      naming: {
        entry: `${name}.mjs`,
        chunk: `${name}-[hash].mjs`,
      },
    });
    if (!result.success) {
      for (const log of result.logs) console.error(log);
      throw new Error(`bundling ${entry} failed`);
    }
    const files = new Map<string, string>();
    for (const file of await readdir(out)) {
      files.set(`lib/${file}`, await readFile(join(out, file), 'utf8'));
    }
    return files;
  } finally {
    await rm(out, { recursive: true, force: true });
  }
}

async function main(): Promise<void> {
  if (!existsSync(join(REPO_ROOT, 'AGENTS.md'))) {
    console.error('Could not find monorepo root at', REPO_ROOT);
    process.exit(1);
  }
  const files = new Map<string, string>([
    ...(await bundle('services/sandbox/src/server.ts', 'sandbox-device')),
    ...(await bundle('services/sandbox-runtime/daemon/src/main.ts', 'runnerd')),
  ]);
  const runtime = join(REPO_ROOT, 'services/sandbox-runtime');
  for (const helper of RAW_HELPERS) {
    files.set(`bin/${helper}`, await readFile(join(runtime, helper), 'utf8'));
  }
  files.set(
    'claude-managed-settings.json',
    await readFile(join(runtime, 'managed-settings.json'), 'utf8'),
  );

  const names = [...files.keys()].sort();
  const digest = createHash('sha256');
  for (const name of names) {
    digest
      .update(name)
      .update('\0')
      .update(files.get(name) ?? '')
      .update('\0');
  }
  const lines: string[] = [
    '// AUTO-GENERATED by scripts/generate-raw-runtime.ts — do not edit',
    '',
    '/** The raw device runtime, by path under its release directory. */',
    'export const RAW_RUNTIME_FILES: Record<string, string> = {',
  ];
  for (const name of names) {
    lines.push(
      `  ${JSON.stringify(name)}: ${JSON.stringify(files.get(name))},`,
    );
  }
  lines.push('};');
  lines.push('');
  lines.push(
    '/** What the files hash to: a laid-out runtime is reused only when it',
  );
  lines.push(' * was laid out from these very files. */');
  lines.push(
    `export const RAW_RUNTIME_DIGEST = ${JSON.stringify(digest.digest('hex'))};`,
  );
  lines.push('');
  const outPath = join(CLI_ROOT, 'src', 'generated', 'raw-runtime.ts');
  await Bun.write(outPath, lines.join('\n'));
  console.log(
    `Raw device runtime: ${names.length} files written to ${relative(CLI_ROOT, outPath)}`,
  );
}

if (import.meta.main) await main();
