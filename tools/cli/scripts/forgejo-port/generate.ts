/**
 * Generate `.forgejo/` from `.github/`: the whole port, as a function of text.
 *
 * Nothing here reads a disk or a network: the sources go in as strings and the files
 * come out as strings, with what was done said once in the report and what Forgejo
 * would refuse said in `problems`. The command line (`../forgejo-port.ts`) is the
 * only thing that touches files.
 */

import { isMap } from 'yaml';

import {
  externalActions,
  registryLogin,
  rewriteActions,
  rewriteLocalActions,
} from './actions';
import { buildCache } from './cache';
import type { Rule } from './context';
import { MANIFEST, planFor, type Manifest, type Plan } from './manifest';
import { portAction, portWorkflow } from './port';
import { DEFAULT_RULES } from './rules';
import { validateAction, validateWorkflow, type Problem } from './validate';
import {
  emptyReport,
  jobOf,
  readWorkflow,
  stringOf,
  type Report,
} from './workflow';
import {
  dropForeignRows,
  dropJobs,
  githubApiToken,
  lintLinksBase,
  movePaths,
  ownPath,
  publishOnTag,
  publishRemote,
  readyJob,
  recordRemoved,
  runUrls,
} from './workflow-rules';

export interface Sources {
  /** `.github/workflows/<file>` by file name. */
  readonly workflows: ReadonlyMap<string, string>;
  /** `.github/actions/<name>/action.yml` by action name. */
  readonly actions: ReadonlyMap<string, string>;
  /** Other repository files the generated workflows use, by path. */
  readonly files: ReadonlyMap<string, string>;
}

export interface WorkflowOutcome {
  readonly file: string;
  readonly plan: Plan;
  /** The generated jobs, when it was ported. */
  readonly jobs: readonly string[];
  /** The jobs of the GitHub file that are not in the generated one, with why. */
  readonly removed: ReadonlyMap<string, string>;
  readonly events: readonly string[];
}

export interface Generated {
  /** Repository path to text. */
  readonly files: ReadonlyMap<string, string>;
  readonly outcomes: readonly WorkflowOutcome[];
  /** `<workflow> / <job>` of every readiness job: what a pull request waits for. */
  readonly checks: readonly string[];
  readonly report: Report;
  /** What Forgejo would refuse in the files above. Empty when the port is sound. */
  readonly problems: readonly Problem[];
  /** The external actions the files use, by `owner/name`, with the refs they pin: what the node must mirror. */
  readonly actions: ReadonlyMap<string, readonly string[]>;
}

export const WORKFLOW_DIR = '.forgejo/workflows';
const ACTION_DIR = '.forgejo/actions';

const HEADER = (from: string): string =>
  `# Generated by tools/cli/scripts/forgejo-port from ${from}.\n` +
  '# Once Tale is built on Forgejo this is the file to edit, by hand: the generator is for the cut-over.\n';

/** The rules every ported workflow goes through, in order. */
function rulesFor(
  plan: Extract<Plan, { kind: 'port' }>,
  manifest: Manifest,
): Rule[] {
  const moves = [
    ...manifest.scripts.map((script) => ({ from: script.from, to: script.to })),
    // A push to main runs for the paths GitHub's workflow lists, and the composites
    // it names are edited in their Forgejo copies.
    ...manifest.composites.map((name) => ({
      from: `.github/actions/${name}/`,
      to: `${ACTION_DIR}/${name}/`,
    })),
  ];
  return [
    dropJobs(plan.dropJobs ?? []),
    ...DEFAULT_RULES,
    dropForeignRows(manifest.labels),
    readyJob,
    rewriteActions,
    buildCache,
    registryLogin(manifest.registry),
    rewriteLocalActions({
      composites: manifest.composites,
      scripts: manifest.scripts.map((script) => script.from),
    }),
    movePaths(moves),
    runUrls,
    lintLinksBase,
    publishRemote,
    publishOnTag,
    githubApiToken(manifest.githubApiTokenSecret),
    ownPath,
  ];
}

export function generate(
  sources: Sources,
  manifest: Manifest = MANIFEST,
): Generated {
  const files = new Map<string, string>();
  const report = emptyReport();
  const problems: Problem[] = [];
  const outcomes: WorkflowOutcome[] = [];
  const checks: string[] = [];

  for (const [file, source] of [...sources.workflows].toSorted(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const plan = planFor(manifest, file);
    if (plan.kind !== 'port') {
      outcomes.push({ file, plan, jobs: [], removed: new Map(), events: [] });
      continue;
    }
    const ported = portWorkflow(source, file, report, {
      rules: rulesFor(plan, manifest),
      after: [recordRemoved],
      triggers: { dropEvents: plan.dropEvents ?? [] },
    });
    const path = `${WORKFLOW_DIR}/${file}`;
    const text = HEADER(`.github/workflows/${file}`) + ported.text;
    files.set(path, text);
    outcomes.push({
      file,
      plan,
      jobs: ported.jobs,
      removed: ported.removed,
      events: ported.events,
    });
    problems.push(...validateWorkflow(text, path, { labels: manifest.labels }));
    const doc = readWorkflow(ported.text, file);
    const name = isMap(doc.contents)
      ? stringOf(doc.contents.get('name'))
      : undefined;
    const ready = jobOf(doc, 'ci-ready');
    const readyName = ready && stringOf(ready.get('name'));
    if (name !== undefined && readyName !== undefined)
      checks.push(`${name} / ${readyName}`);
  }

  for (const name of manifest.composites) {
    const source = sources.actions.get(name);
    if (source === undefined) {
      problems.push({
        file: `.github/actions/${name}/action.yml`,
        at: '',
        message: 'is named by the manifest and does not exist',
      });
      continue;
    }
    const path = `${ACTION_DIR}/${name}/action.yml`;
    const text =
      HEADER(`.github/actions/${name}/action.yml`) +
      portAction(source, path, report, [rewriteActions]);
    files.set(path, text);
    problems.push(...validateAction(text, path));
  }

  for (const script of manifest.scripts) {
    const source = sources.files.get(script.from);
    if (source === undefined) {
      problems.push({
        file: script.from,
        at: '',
        message: 'is named by the manifest and does not exist',
      });
      continue;
    }
    let text = source;
    for (const edit of script.edits) {
      if (!text.includes(edit.find)) {
        problems.push({
          file: script.from,
          at: '',
          message: `the line \`${edit.find}\` is gone: the copy would still say GHCR`,
        });
        continue;
      }
      text = text.replaceAll(edit.find, edit.replace);
    }
    files.set(script.to, text);
  }

  return {
    files,
    outcomes,
    checks: checks.toSorted(),
    report,
    problems,
    actions: usedActions(files),
  };
}

/** The external actions of the generated workflows and composite actions. */
function usedActions(
  files: ReadonlyMap<string, string>,
): Map<string, string[]> {
  const found = new Map<string, Set<string>>();
  for (const [path, text] of files) {
    if (!path.endsWith('.yml')) continue;
    for (const { name, ref } of externalActions(readWorkflow(text, path)))
      found.set(name, (found.get(name) ?? new Set()).add(ref));
  }
  return new Map(
    [...found]
      .toSorted(([a], [b]) => a.localeCompare(b))
      .map(([name, refs]) => [name, [...refs].toSorted()]),
  );
}
