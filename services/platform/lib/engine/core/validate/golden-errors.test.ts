// ------------------------------------------------------------------- tests

interface RenderedCase {
  errors: Array<Record<string, unknown>>;
  warnings: Array<Record<string, unknown>>;
}

function renderIssue(issue: Issue): Record<string, unknown> {
  const out: Record<string, unknown> = { code: issue.code };
  if (issue.nodeId !== undefined) out.nodeId = issue.nodeId;
  if (issue.path !== undefined) out.path = issue.path;
  out.message = issue.message;
  if (issue.hint !== undefined) out.hint = issue.hint;
  return out;
}

async function renderCorpus(): Promise<Record<string, RenderedCase>> {
  const rendered: Record<string, RenderedCase> = {};
  for (const [name, doc] of Object.entries(fixtures)) {
    const { errors, warnings } = await validate(doc);
    rendered[name] = {
      errors: errors.map(renderIssue),
      warnings: warnings.map(renderIssue),
    };
  }
  return rendered;
}

it('renders exactly the pinned issue lists', async () => {
  const actual = await renderCorpus();
  if (process.env.GOLDEN_UPDATE === '1') {
    writeFileSync(GOLDEN_PATH, HEADER + stringify(actual, { lineWidth: 0 }));
    return;
  }
  const golden: unknown = parse(readFileSync(GOLDEN_PATH, 'utf8'));
  expect(actual).toEqual(golden);
});

it('covers every validation code at least once', async () => {
  const rendered = await renderCorpus();
  const emitted = new Set<string>();
  for (const { errors, warnings } of Object.values(rendered)) {
    for (const issue of [...errors, ...warnings]) {
      if (typeof issue.code === 'string') emitted.add(issue.code);
    }
  }
  const byName = (a: string, b: string) => a.localeCompare(b);
  expect([...emitted].sort(byName)).toEqual([...VALIDATION_CODES].sort(byName));
});
