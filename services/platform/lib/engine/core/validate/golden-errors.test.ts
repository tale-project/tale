function flow(over: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    version: 1,
    name: 'fixture-flow',
    nodes: [{ id: 'main', type: 'transform', code: 'return 1;' }],
    output: '{{ nodes.main.output }}',
    ...over,
  };
}

function chainOf(count: number): Record<string, unknown> {
  const nodes = Array.from({ length: count }, (_, i) => ({
    id: `t${i}`,
    type: 'transform',
    code: i === 0 ? 'return 1;' : `return nodes.t${i - 1}.output;`,
  }));
  return flow({ nodes, output: `{{ nodes.t${count - 1}.output }}` });
}

